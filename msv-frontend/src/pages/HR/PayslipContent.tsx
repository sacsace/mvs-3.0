/** 표시용 회사명 — Private Limited / Pvt Ltd 등 법적 접미사 제거 */
export function shortCompanyName(name?: string | null): string {
  return String(name || '')
    .replace(/\bprivate\s+limited\b\.?/gi, '')
    .replace(/\bpvt\.?\s*ltd\.?\b/gi, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/[,\s]+$/g, '')
    .trim();
}

