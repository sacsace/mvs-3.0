/** 객체/[object Object]는 빈 값으로 — 화면에 그대로 노출하지 않음 */
function displayText(value: unknown): string {
  if (value == null || value === '') return '';
  if (typeof value === 'object') {
    if (value instanceof Date && !Number.isNaN(value.getTime())) {
      return formatDateOnly(value);
    }
    return '';
  }
  const s = String(value).trim();
  if (!s || /^\[object\s+object\]$/i.test(s)) return '';
  return s;
}

/** 입사일 등 — YYYY-MM-DD만 */
function formatDateOnly(value: unknown): string {
  if (value == null || value === '') return '';
  if (value instanceof Date && !Number.isNaN(value.getTime())) {
    const y = value.getFullYear();
    const m = String(value.getMonth() + 1).padStart(2, '0');
    const d = String(value.getDate()).padStart(2, '0');
    return `${y}-${m}-${d}`;
  }
  if (typeof value === 'object') return '';
  const s = String(value).trim();
  if (!s || /^\[object\s+object\]$/i.test(s)) return '';
  const iso = s.match(/^(\d{4})[./-](\d{1,2})[./-](\d{1,2})/);
  if (iso) {
    return `${iso[1]}-${iso[2].padStart(2, '0')}-${iso[3].padStart(2, '0')}`;
  }
  const parsed = new Date(s);
  if (!Number.isNaN(parsed.getTime()) && (/\bGMT\b/i.test(s) || /[A-Za-z]{3}/.test(s))) {
    const y = parsed.getFullYear();
    const m = String(parsed.getMonth() + 1).padStart(2, '0');
    const d = String(parsed.getDate()).padStart(2, '0');
    return `${y}-${m}-${d}`;
  }
  return s;
}

function parseMoney(v: string | number | undefined | null): number {
  if (v === '' || v == null) return 0;
  if (typeof v === 'number') return Number.isFinite(v) ? v : 0;
  const n = parseFloat(String(v).replace(/,/g, '').trim());
  return Number.isFinite(n) ? n : 0;
}

/** 급여 명세서 금액 — 정수 내림 */
export function money(n: number): string {
  return `INR ${Math.floor(Number(n || 0)).toLocaleString(INR, { maximumFractionDigits: 0 })}`;
}

function moneyFromField(v: string | number | undefined | null): string {
  return money(parseMoney(v));
}

function statementDateFromPeriod(period: string): string {
  const p = displayText(period);
  if (!p || !/^\d{4}-\d{2}$/.test(p)) return '';
  const [y, m] = p.split('-').map(Number);
  const last = new Date(y, m, 0);
  return last.toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });
}

const BELOW_20 = [
  '',
  'One',
  'Two',
  'Three',
  'Four',
  'Five',
  'Six',
  'Seven',
  'Eight',
  'Nine',
  'Ten',
  'Eleven',
  'Twelve',
  'Thirteen',
  'Fourteen',
  'Fifteen',
  'Sixteen',
  'Seventeen',
  'Eighteen',
  'Nineteen'
];
const TENS = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

function twoDigits(n: number): string {
  if (n < 20) return BELOW_20[n];
  const t = Math.floor(n / 10);
  const o = n % 10;
  return `${TENS[t]}${o ? `-${BELOW_20[o]}` : ''}`.trim();
}

function threeDigits(n: number): string {
  if (n === 0) return '';
  const h = Math.floor(n / 100);
  const rest = n % 100;
  if (h) return `${BELOW_20[h]} Hundred${rest ? ` and ${twoDigits(rest)}` : ''}`;
  return twoDigits(rest);
}

function inrWordsCore(n: number): string {
  if (n === 0) return '';
  const crore = Math.floor(n / 10000000);
  const lakh = Math.floor((n % 10000000) / 100000);
  const thousand = Math.floor((n % 100000) / 1000);
  const hundred = n % 1000;
  const parts: string[] = [];
  if (crore) parts.push(`${inrWordsCore(crore)} Crore`.trim());
  if (lakh) parts.push(`${twoDigits(lakh)} Lakh`);
  if (thousand) parts.push(`${twoDigits(thousand)} Thousand`);
  if (hundred) parts.push(threeDigits(hundred));
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

export function inrAmountInWords(amount: number): string {
  const n = Math.floor(Number(amount || 0));
  if (n === 0) return 'Zero Only';
  return `${inrWordsCore(n)} Only`;
}

