const PayslipContent = React.forwardRef<HTMLDivElement, Props>(function PayslipContent(
  {
    row,
    labels,
    companyInfo,
    companyId,
    showTitle = true,
    wide = false,
    forPdf = false,
    headerLayout = 'standard'
  },
  ref
) {
  const dayHours = parseMoney(row.day_ot_hour);
  const otRate = parseMoney(row.ot_rate);
  const otPayTotal = Math.floor(dayHours * otRate);

  const grossPay = parseMoney(row.sum_total);
  const pfEmp = parseMoney(row.pf_employee);
  const esicEmp = parseMoney(row.esic_employee);
  const tdsAmt = parseMoney(row.tds);
  const ptAmt = parseMoney(row.pt);
  const otherDeduct = Math.max(0, parseMoney(row.deduct_this_month) - (pfEmp + esicEmp + tdsAmt + ptAmt));
  const totalDeductions =
    parseMoney(row.deduct_this_month) > 0
      ? parseMoney(row.deduct_this_month)
      : pfEmp + esicEmp + tdsAmt + ptAmt + otherDeduct;
  const netPay = parseMoney(row.net_salary_payable);

  const dayOtLabel =
    dayHours > 0 ? `${labels.dayOt} (${formatOtHourDisplay(dayHours)}h)` : labels.dayOt;

  const companyName = shortCompanyName(companyInfo?.name) || '—';
  const companyContact = [companyInfo?.address, companyInfo?.phone, companyInfo?.email]
    .filter((x) => !!String(x || '').trim())
    .join(' · ');

  // 엑셀 등에서 넘어온 수당 행이 있으면 리스트(열) 그대로 표시
  const customLines = Array.isArray(row.payslip_earning_lines) ? row.payslip_earning_lines : [];
  const earningItems: LedgerLine[] = customLines.length
    ? customLines.map((line) => ({
        label: line.label,
        value: money(line.amount),
        highlight: line.highlight,
      }))
    : [
        ...(() => {
          const ratios = loadPayrollSalaryRatios(companyId);
          const lines = ratios.parts.map((part) => {
            let amount = 0;
            if (part.id === 'basic_salary') amount = Number(row.basic_salary) || 0;
            else if (part.id === 'house_rent_allowance') amount = Number(row.house_rent_allowance) || 0;
            else if (part.id === 'other_allowance') amount = Number(row.other_allowance) || 0;
            else amount = Number(row.constant_parts?.[part.id]) || 0;
            return { label: part.label, value: money(amount) };
          });
          // 설정에 없는 상수 항목도 금액이 있으면 누락 없이 표시
          const known = new Set(ratios.parts.map((p) => p.id));
          Object.entries(row.constant_parts || {}).forEach(([id, amount]) => {
            if (known.has(id) || !(Number(amount) > 0)) return;
            lines.push({ label: id.replace(/_/g, ' '), value: money(amount) });
          });
          return lines;
        })(),
        ...(Number(row.food_allowance) > 0
          ? [{ label: labels.foodAllowance, value: money(row.food_allowance) }]
          : []),
        ...(dayHours > 0
          ? [{ label: dayOtLabel, value: money(otPayTotal), highlight: true }]
          : dayHours === 0 && otPayTotal === 0
            ? [{ label: labels.dayOt, value: money(0), highlight: true }]
            : []),
        { label: labels.extraAllowance, value: money(row.transport_allowance), highlight: true },
        ...(() => {
          const prefs = loadPayrollColumnPrefs(companyId);
          return Object.entries(row.custom_allowances || {})
            .filter(([, amount]) => Number(amount) > 0)
            .map(([key, amount]) => {
              const label =
                prefs.customColumns.find((c) => c.id === key)?.label ||
                key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
              return { label, value: money(amount), highlight: true };
            });
        })(),
      ];

  const deductionItems: LedgerLine[] = [
    { label: labels.pfEmployee, value: moneyFromField(row.pf_employee) },
    { label: labels.esicEmployee, value: moneyFromField(row.esic_employee) },
    { label: labels.pt, value: moneyFromField(row.pt) },
    { label: labels.tds, value: money(row.tds) }
  ];
  if (otherDeduct > 0) {
    deductionItems.push({ label: labels.deductMonth, value: money(otherDeduct) });
  }

  return (
    <Box
      ref={ref}
      sx={{
        bgcolor: forPdf ? '#FFFFFF' : 'bodyArea.main',
        color: 'text.primary',
        p: wide || forPdf ? 0 : { xs: 0, sm: 0.5 },
        width: wide || forPdf ? '100%' : undefined,
        maxWidth: wide || forPdf ? '100%' : 760,
        mx: wide || forPdf ? 0 : 'auto',
        boxSizing: 'border-box'
      }}
    >
      <Box sx={{ ...mvsBodyCardSx, overflow: 'hidden' }}>
        <PayslipHeader
          labels={labels}
          showTitle={showTitle}
          employeeName={displayText(row.employee_name)}
          workingMonth={displayText(row.working_month)}
          paidDays={displayText(row.days_worked)}
          companyName={companyName}
          companyContact={companyContact}
          companyLogo={companyInfo?.logo}
          forPdf={forPdf}
          layout={headerLayout}
        />

        <Box sx={{ px: { xs: 2, sm: 2.5 }, pb: forPdf ? 1.5 : 2.5, pt: forPdf ? 1.5 : 2.5 }}>
          {/* 직원 정보 — A4 한 페이지를 위해 3열 */}
          <SectionHeading compact={forPdf}>{labels.employee}</SectionHeading>
          <Box sx={{ ...mvsBodyTableInsetSx, mb: forPdf ? 1.5 : 3, borderRadius: '8px', overflow: 'hidden' }}>
            <Box
              sx={{
                ...mvsBodyTableFrameSx,
                p: forPdf ? 1.25 : { xs: 1.5, sm: 2 },
                display: 'grid',
                gridTemplateColumns: forPdf ? '1fr 1fr 1fr' : { xs: '1fr', sm: '1fr 1fr 1fr' },
                columnGap: forPdf ? 2 : 2.5,
                rowGap: 0
              }}
            >
              <EmpField compact={forPdf} label={labels.workingMonth} value={row.working_month} />
              <EmpField
                compact={forPdf}
                label={labels.statementDate}
                value={statementDateFromPeriod(displayText(row.working_month))}
              />
              <EmpField compact={forPdf} label={labels.totalDaysInMonth} value={row.total_day_of_month} />
              <EmpField compact={forPdf} label={labels.paidDays} value={row.days_worked} />
              <EmpField
                compact={forPdf}
                label={labels.unpaidLeave}
                value={displayText(row.unpaid_leave) || '0'}
                highlight
              />
              <EmpField compact={forPdf} label={labels.empId} value={row.emp_id} />
              <EmpField
                compact={forPdf}
                label={labels.designation}
                value={formatPositionLabel(row.position, 'en', false)}
              />
              <EmpField compact={forPdf} label={labels.email} value={row.employee_email} link />
              <EmpField compact={forPdf} label={labels.dateOfJoin} value={row.joining_date} dateOnly />
              <EmpField compact={forPdf} label={labels.department} value={row.department} />
              <EmpField compact={forPdf} label={labels.bank} value={row.bank_name} />
              <EmpField compact={forPdf} label={labels.account} value={row.bank_account} />
              <EmpField compact={forPdf} label={labels.ifsc} value={row.ifsc} />
            </Box>
          </Box>

          {/* 지급 · 공제 — 합계 행 정렬 */}
          <SectionHeading compact={forPdf}>{labels.earningsAndDeductions}</SectionHeading>
          <EarningsDeductionsTable
            labels={labels}
            earningItems={earningItems}
            deductionItems={deductionItems}
            grossPay={grossPay}
            totalDeductions={totalDeductions}
            forPdf={forPdf}
          />

          {/* 실수령 — Body 내부 카드 */}
          <Box
            sx={{
              ...mvsInnerCardSx,
              mb: forPdf ? 1 : 2,
              border: '2px solid',
              borderColor: 'primary.light',
              bgcolor: 'primary.50',
              borderRadius: '8px',
              overflow: 'hidden',
              py: forPdf ? 1.25 : undefined,
              px: forPdf ? 1.5 : undefined,
            }}
          >
            <Typography
              sx={{
                fontWeight: 700,
                color: 'primary.main',
                fontSize: forPdf ? '0.75rem' : '0.85rem',
                mb: 0.5,
              }}
            >
              {labels.netPay}
            </Typography>
            <Typography
              sx={{
                fontWeight: 700,
                fontSize: forPdf ? '1.45rem' : { xs: '1.65rem', sm: '1.9rem' },
                color: 'text.primary',
                fontVariantNumeric: 'tabular-nums',
                lineHeight: 1.15,
                mb: forPdf ? 0.5 : 1,
                letterSpacing: '-0.02em'
              }}
            >
              {money(netPay)}
            </Typography>
            <Typography
              sx={{
                ...mvsPageDescriptionSx,
                color: 'success.dark',
                fontWeight: 600,
                fontSize: forPdf ? '0.72rem' : undefined,
              }}
            >
              {labels.amountInWords}: {inrAmountInWords(netPay)}
            </Typography>
          </Box>

          <Typography
            variant="caption"
            sx={{
              ...mvsPageDescriptionSx,
              display: 'block',
              textAlign: 'center',
              fontSize: forPdf ? '0.65rem' : undefined,
            }}
          >
            {labels.autoGenerated}
          </Typography>
        </Box>
      </Box>
    </Box>
  );
});

export default PayslipContent;
