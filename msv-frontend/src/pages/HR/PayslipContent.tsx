const USER_INPUT_COLOR = '#B91C1C';

function EmpField({
  label,
  value,
  link,
  highlight
}: {
  label: string;
  value: string;
  link?: boolean;
  highlight?: boolean;
}) {
  return (
    <Box sx={{ py: 0.75 }}>
      <Typography variant="caption" color="text.secondary" sx={{ display: 'block', fontWeight: 600, mb: 0.35 }}>
        {label}
      </Typography>
      <Typography
        variant="body2"
        sx={{
          fontWeight: 600,
          color: highlight ? USER_INPUT_COLOR : link ? 'info.main' : 'text.primary',
          wordBreak: 'break-word'
        }}
      >
        {value || '—'}
      </Typography>
    </Box>
  );
}

function LedgerRow({
  label,
  value,
  total,
  totalTone,
  isLast,
  highlight
}: {
  label: string;
  value: string;
  total?: boolean;
  totalTone?: 'earn' | 'deduct';
  isLast?: boolean;
  highlight?: boolean;
}) {
  const earnTotal = total && totalTone === 'earn';
  const deductTotal = total && totalTone === 'deduct';
  const highlightColor = highlight ? USER_INPUT_COLOR : undefined;
  return (
    <Box
      sx={{
        display: 'flex',
        justifyContent: 'space-between',
        alignItems: 'center',
        gap: 1.5,
        px: 2,
        py: 1.25,
        minHeight: 44,
        borderBottom: isLast ? 'none' : `1px solid ${MVS_ROW_BORDER}`,
        bgcolor: earnTotal ? 'primary.50' : '#FFFFFF'
      }}
    >
      <Typography
        variant="body2"
        sx={{
          fontWeight: total ? 700 : 500,
          color: highlightColor ?? (earnTotal ? 'primary.main' : deductTotal ? 'warning.dark' : 'text.secondary'),
          fontSize: '0.8125rem'
        }}
      >
        {label}
      </Typography>
      <Typography
        variant="body2"
        sx={{
          fontWeight: total ? 700 : 600,
          fontVariantNumeric: 'tabular-nums',
          color: highlightColor ?? (earnTotal ? 'primary.main' : deductTotal ? 'warning.dark' : 'text.primary'),
          whiteSpace: 'nowrap',
          fontSize: '0.8125rem'
        }}
      >
        {value}
      </Typography>
    </Box>
  );
}

