type LedgerLine = { label: string; value: string; highlight?: boolean };

function EarningsDeductionsTable({
  labels,
  earningItems,
  deductionItems,
  grossPay,
  totalDeductions,
  forPdf
}: {
  labels: PayslipLabels;
  earningItems: LedgerLine[];
  deductionItems: LedgerLine[];
  grossPay: number;
  totalDeductions: number;
  forPdf?: boolean;
}) {
  const rowCount = Math.max(earningItems.length, deductionItems.length);
  const detailRows = Array.from({ length: rowCount }, (_, index) => ({
    earn: earningItems[index] ?? null,
    deduct: deductionItems[index] ?? null
  }));

  const gridColumns = forPdf ? '1fr 1px 1fr' : { xs: '1fr', md: '1fr 1px 1fr' };
  const dividerDisplay = forPdf ? 'block' : { xs: 'none', md: 'block' };

  return (
    <Box sx={{ ...mvsBodyTableFrameSx, mb: 2.5, overflow: 'hidden' }}>
      <Box sx={{ display: 'grid', gridTemplateColumns: gridColumns }}>
        <LedgerColumnHeader title={labels.earnings} />
        <Box sx={{ display: dividerDisplay, bgcolor: '#C5CED9' }} />
        <LedgerColumnHeader title={labels.employeeDeductions} />
      </Box>

      {detailRows.map((line, index) => (
        <Box key={`ledger-${index}`} sx={{ display: 'grid', gridTemplateColumns: gridColumns }}>
          {line.earn ? (
            <LedgerRow
              label={line.earn.label}
              value={line.earn.value}
              highlight={line.earn.highlight}
            />
          ) : (
            <LedgerSpacer />
          )}
          <Box sx={{ display: dividerDisplay, bgcolor: '#C5CED9' }} />
          {line.deduct ? (
            <LedgerRow label={line.deduct.label} value={line.deduct.value} />
          ) : (
            <LedgerSpacer />
          )}
        </Box>
      ))}

      <Box
        sx={{
          display: 'grid',
          gridTemplateColumns: gridColumns,
          borderTop: `1px solid ${MVS_ROW_BORDER}`
        }}
      >
        <LedgerRow
          label={labels.grossSalary}
          value={money(grossPay)}
          total
          totalTone="earn"
          isLast
        />
        <Box sx={{ display: dividerDisplay, bgcolor: '#C5CED9' }} />
        <LedgerRow
          label={labels.totalDeductions}
          value={money(totalDeductions)}
          total
          totalTone="deduct"
          isLast
        />
      </Box>
    </Box>
  );
}

